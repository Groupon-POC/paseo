// Changed for Groupon Desk (fork of Paseo, Apache-2.0): also writes the runtime as a script file under public/ for pages whose policy forbids inline script.
import esbuild from "esbuild";
import { createHash } from "node:crypto";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(__dirname, "../../../../..");
const repoRoot = path.resolve(appRoot, "../..");
const entry = path.join(__dirname, "runtime/entry.ts");
const output = path.join(__dirname, "runtime/html.gen.ts");
const publicDir = path.join(appRoot, "public");
const scriptFileOutput = path.join(__dirname, "runtime/script-file.gen.ts");

const result = await esbuild.build({
  entryPoints: [entry],
  bundle: true,
  write: false,
  format: "iife",
  platform: "browser",
  target: ["ios15", "chrome100"],
  minify: true,
  // The app's deployment floor is iOS 15.1 but structuredClone (used by
  // mermaid) only exists from iOS 15.4; esbuild targets transform syntax,
  // not runtime APIs. Mermaid only clones plain config objects, so a
  // JSON-based fallback is sufficient.
  banner: {
    js: 'if(typeof globalThis.structuredClone!=="function"){globalThis.structuredClone=function(v){return v===undefined?v:JSON.parse(JSON.stringify(v));};}',
  },
  logLevel: "info",
});

const rawJs = result.outputFiles[0]?.text;
if (!rawJs) {
  throw new Error("Mermaid runtime bundle produced no JavaScript");
}
// JSON.stringify below escapes the TypeScript representation, not the runtime
// HTML — an embedded closing-script sequence would still terminate the inline
// <script>. `<\/script` is identical to `</script` inside JS strings/regex.
const js = rawJs.replace(/<\/script/gi, "<\\/script");

const html = `<!doctype html>
<html>
  <head>
    <meta charset="utf-8" />
    <meta
      http-equiv="Content-Security-Policy"
      content="default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; connect-src 'none'; img-src data: blob:; font-src 'none'; media-src 'none'; object-src 'none'; frame-src 'none'; base-uri 'none'; form-action 'none'"
    />
    <meta
      name="viewport"
      content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no, viewport-fit=cover"
    />
    <style>
      html,
      body {
        margin: 0;
        padding: 0;
        background: transparent;
        height: 100%;
      }
      /* The host sizes this frame to the diagram, so the diagram fills the frame. */
      #diagram {
        height: 100%;
      }
      #diagram svg {
        display: block;
      }
    </style>
  </head>
  <body>
    <div id="diagram"></div>
    <script>${js}</script>
  </body>
</html>`;

const contents = `// Generated by packages/app/src/components/markdown/fence/mermaid/build-runtime.mjs.
// Do not edit by hand.

export const mermaidRuntimeHtml = ${JSON.stringify(html)};
`;

await fs.writeFile(output, contents);
console.log(`Wrote ${path.relative(repoRoot, output)} (${html.length} bytes)`);

// The same bundle as a file the web build serves from its own origin. A page whose Content
// Security Policy forbids inline script (the work window on the web) cannot run the inline copy
// above, and a srcdoc or blob: frame inherits that policy, so the frame loads this file instead.
// The content hash is in the name: a deploy that changes the runtime is a different URL.
const scriptFile = `mermaid-runtime.${createHash("sha256").update(rawJs).digest("hex").slice(0, 10)}.js`;
for (const name of await fs.readdir(publicDir)) {
  if (/^mermaid-runtime\.[0-9a-f]+\.js$/.test(name) && name !== scriptFile) {
    await fs.rm(path.join(publicDir, name));
  }
}
await fs.writeFile(path.join(publicDir, scriptFile), rawJs);
await fs.writeFile(
  scriptFileOutput,
  `// Added for Groupon Desk (fork of Paseo, Apache-2.0): the name of the Mermaid runtime's script file under public/.
// Generated by packages/app/src/components/markdown/fence/mermaid/build-runtime.mjs.
// Do not edit by hand.

export const mermaidRuntimeScriptFile = ${JSON.stringify(scriptFile)};
`,
);
console.log(`Wrote packages/app/public/${scriptFile} (${rawJs.length} bytes)`);
